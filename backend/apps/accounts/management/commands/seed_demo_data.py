    # ------------------------------------------------------------------
    # Step 5: Approve issuer1 (real blockchain call)
    # ------------------------------------------------------------------
    def _approve_institution(self, institution: Institution, admin_user: User) -> bool:
        self._heading("Step 5 — Approve issuer1 institution (on-chain whitelist)")

        if institution.status == InstitutionStatus.APPROVED:
            self._skip(
                f"Institution '{institution.name}' is already APPROVED "
                f"(wallet={institution.wallet_address})"
            )
            return True

        if institution.status != InstitutionStatus.PENDING:
            self._err(
                f"Institution '{institution.name}' has status={institution.status}, "
                f"cannot approve (expected PENDING)."
            )
            return False

        # Replicate the exact code path from ApproveInstitutionView.post()
        # 1. Generate custodial wallet if not already present
        if not institution.encrypted_private_key:
            institution.generate_custodial_wallet()

        # 2. On-chain whitelist call
        trust_tier = 1
        try:
            tx_hash = BlockchainService.approve_issuer(
                wallet_address=institution.wallet_address,
                name=institution.name,
                trust_tier=trust_tier,
                related_object_id=institution.id,
            )
        except (BlockchainError, BlockchainRevertError) as exc:
            self._err(f"Blockchain call failed: {exc}")
            self._err(
                "Please ensure Ganache is running (npx ganache --port 7545) "
                "with a deployed CredentialPlatform contract, then re-run:\n"
                "    py manage.py seed_demo_data"
            )
            return False
        except Exception as exc:
            self._err(f"Unexpected error during approval: {exc}")
            self._err(
                "Please start Ganache and re-run: py manage.py seed_demo_data"
            )
            return False

        # 3. Update DB status (mirrors ApproveInstitutionView)
        institution.status = InstitutionStatus.APPROVED
        institution.trust_tier = trust_tier
        institution.reviewed_by = admin_user
        institution.reviewed_at = timezone.now()
        institution.rejection_reason = None
        institution.save()

        self._info(
            f"Institution '{institution.name}' APPROVED on-chain "
            f"(tx={tx_hash}, custodial_wallet={institution.wallet_address})"
        )

        # 3b. Fund the custodial wallet so it can pay gas for credential issuance.
        # On a local Ganache the freshly generated custodial wallet has 0 ETH.
        self._fund_custodial_wallet(institution)

        return True

    def _fund_custodial_wallet(self, institution: Institution):
        """Send 1 ETH from the platform admin wallet to the custodial wallet so it can issue credentials."""
        try:
            w3 = BlockchainService.get_web3()
            admin_pk = BlockchainService.get_admin_private_key()
            admin_account = w3.eth.account.from_key(admin_pk)
            custodial_addr = w3.to_checksum_address(institution.wallet_address)

            balance = w3.eth.get_balance(custodial_addr)
            one_ether = w3.to_wei(1, 'ether')

            if balance >= one_ether:
                self._skip(
                    f"Custodial wallet {custodial_addr} already has "
                    f"{w3.from_wei(balance, 'ether')} ETH -- skipping funding"
                )
                return

            nonce = w3.eth.get_transaction_count(admin_account.address, 'pending')
            tx = {
                'to': custodial_addr,
                'value': one_ether,
                'gas': 21000,
                'gasPrice': w3.eth.gas_price,
                'nonce': nonce,
                'chainId': BlockchainService.get_chain_id(),
            }
            signed = w3.eth.account.sign_transaction(tx, private_key=admin_pk)
            raw = getattr(signed, 'raw_transaction', None) or getattr(signed, 'rawTransaction', None)
            tx_hash_bytes = w3.eth.send_raw_transaction(raw)
            w3.eth.wait_for_transaction_receipt(tx_hash_bytes, timeout=15)

            self._info(
                f"Funded custodial wallet {custodial_addr} with 1 ETH "
                f"(tx={w3.to_hex(tx_hash_bytes)})"
            )
        except Exception as exc:
            self._err(f"Failed to fund custodial wallet: {exc}")
            self._err("Credential issuance will likely fail due to insufficient gas.")

    # ------------------------------------------------------------------
    # Step 6: Issue credentials (real blockchain call)
    # ------------------------------------------------------------------
    def _issue_credentials(self, institution: Institution, student_profile: StudentProfile) -> list:
        self._heading("Step 6 — Issue credentials from issuer1 to student1")
        issued = []

        for idx, spec in enumerate(DEMO_CREDENTIALS):
            doc_content = spec["doc_content"]
            document_hash = compute_document_hash(doc_content)

            # Idempotency: check if credential with this document_hash already exists
            existing = Credential.objects.filter(document_hash__iexact=document_hash).first()
            if existing:
                self._skip(
                    f"Credential '{spec['title']}' already exists "
                    f"(id={existing.id}, status={existing.status})"
                )
                issued.append(existing)
                continue

            # Step 1: IPFS upload
            ipfs_cid = default_ipfs_service.upload_document(doc_content, filename=f"demo_cred_{idx}.pdf")

            # Step 2: Create DB record in PENDING status
            credential = Credential.objects.create(
                student=student_profile,
                institution=institution,
                credential_type=spec["credential_type"],
                title=spec["title"],
                issue_date=spec["issue_date"],
                document_hash=document_hash,
                ipfs_cid=ipfs_cid,
                status=CredentialStatus.PENDING,
            )

            # Step 3: On-chain issuance
            try:
                tx_hash = BlockchainService.issue_credential(
                    credential_id=credential.id,
                    document_hash=document_hash,
                    ipfs_cid=ipfs_cid,
                    issuer_wallet_address=institution.wallet_address,
                    related_object_id=credential.id,
                )
            except (BlockchainError, BlockchainRevertError) as exc:
                self._err(f"Blockchain issuance failed for '{spec['title']}': {exc}")
                self._err("Credential remains PENDING — fix blockchain and re-run.")
                issued.append(credential)
                continue

            # Step 4: Mark ACTIVE
            credential.status = CredentialStatus.ACTIVE
            credential.tx_hash = tx_hash
            credential.save(update_fields=["status", "tx_hash", "updated_at"])

            self._info(
                f"Issued credential '{spec['title']}' "
                f"(id={credential.id}, tx={tx_hash})"
            )
            issued.append(credential)

        return issued

    # ------------------------------------------------------------------
    # Step 7: Revoke one credential (real blockchain call)
    # ------------------------------------------------------------------
    def _revoke_credential(self, credentials: list, institution: Institution):
        self._heading("Step 7 — Revoke one credential for demo verification")

        if REVOKE_INDEX >= len(credentials):
            self._err(f"Revoke index {REVOKE_INDEX} out of range ({len(credentials)} credentials)")
            return

        target = credentials[REVOKE_INDEX]

        if target.status == CredentialStatus.REVOKED:
            self._skip(
                f"Credential '{target.title}' is already REVOKED (id={target.id})"
            )
            return

        if target.status != CredentialStatus.ACTIVE:
            self._err(
                f"Credential '{target.title}' has status={target.status}, "
                f"cannot revoke (expected ACTIVE)."
            )
            return

        try:
            tx_hash = BlockchainService.revoke_credential(
                credential_id=target.id,
                issuer_wallet_address=institution.wallet_address,
                related_object_id=target.id,
            )
        except (BlockchainError, BlockchainRevertError) as exc:
            self._err(f"Blockchain revocation failed: {exc}")
            return

        target.status = CredentialStatus.REVOKED
        target.tx_hash = tx_hash
        target.revoked_at = timezone.now()
        target.revocation_reason = "Demo revocation — credential voided for testing purposes"
        target.save(update_fields=["status", "tx_hash", "revoked_at", "revocation_reason", "updated_at"])

        self._info(
            f"Revoked credential '{target.title}' (id={target.id}, tx={tx_hash})"
        )

