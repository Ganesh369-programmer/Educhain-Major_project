    # ------------------------------------------------------------------
    # Reset
    # ------------------------------------------------------------------
    def _reset(self):
        self._heading("RESET -- Removing demo data")

        # Collect demo institution IDs via issuer profiles (before deleting anything)
        issuer_emails = [u["email"] for u in DEMO_USERS if u["role"] == UserRole.ISSUER]
        demo_inst_ids = list(
            IssuerProfile.objects.filter(
                user__email__in=issuer_emails
            ).values_list("institution_id", flat=True)
        )

        # Also catch institutions by known names (fallback if profiles were already gone)
        DEMO_INSTITUTION_NAMES = ["State University of Example", "Fake Cert Institute"]
        name_ids = list(
            Institution.objects.filter(name__in=DEMO_INSTITUTION_NAMES)
            .values_list("id", flat=True)
        )
        demo_inst_ids = list(set(demo_inst_ids) | set(name_ids))

        # Credentials from demo institutions
        cred_count, _ = Credential.objects.filter(institution_id__in=demo_inst_ids).delete()
        self._info(f"Deleted {cred_count} credential records")

        # Blockchain transactions related to demo institutions
        tx_count, _ = BlockchainTransaction.objects.filter(related_object_id__in=demo_inst_ids).delete()
        self._info(f"Deleted {tx_count} blockchain transaction records (institution-related)")

        # IssuerProfiles
        ip_count, _ = IssuerProfile.objects.filter(
            user__email__in=issuer_emails
        ).delete()
        self._info(f"Deleted {ip_count} issuer profile records")

        # Institutions
        inst_count, _ = Institution.objects.filter(id__in=demo_inst_ids).delete()
        self._info(f"Deleted {inst_count} institution records")

        # StudentProfiles
        sp_count, _ = StudentProfile.objects.filter(user__email__in=DEMO_EMAILS).delete()
        self._info(f"Deleted {sp_count} student profile records")

        # Users
        u_count, _ = User.objects.filter(email__in=DEMO_EMAILS).delete()
        self._info(f"Deleted {u_count} user records")

    # ------------------------------------------------------------------
    # Step 1: Users
    # ------------------------------------------------------------------
    def _create_users(self) -> dict:
        self._heading("Step 1 — Users")
        users = {}
        for spec in DEMO_USERS:
            email = spec["email"]
            existing = User.objects.filter(email__iexact=email).first()
            if existing:
                self._skip(f"User {email} already exists (id={existing.id})")
                users[email] = existing
                continue

            extra = {}
            if spec.get("is_staff"):
                extra["is_staff"] = True
            if spec.get("is_superuser"):
                extra["is_superuser"] = True

            if spec["role"] == UserRole.ADMIN:
                user = User.objects.create_superuser(
                    email=email,
                    password=DEMO_PASSWORD,
                    role=UserRole.ADMIN,
                    **extra,
                )
            else:
                user = User.objects.create_user(
                    email=email,
                    password=DEMO_PASSWORD,
                    role=spec["role"],
                    **extra,
                )
            self._info(f"Created user {email} (role={spec['role']}, id={user.id})")
            users[email] = user
        return users

